<?php

require_once "auth.php";


$currentPage = basename($_SERVER['PHP_SELF']);


/*
|--------------------------------------------------------------------------
| Cashier Allowed Pages
|--------------------------------------------------------------------------
*/

$cashierPages = [

    "pos.php",
    "logout.php"

];



/*
|--------------------------------------------------------------------------
| Public Pages
|--------------------------------------------------------------------------
*/

$publicPages = [

    "login.php",
    "register.php"

];



/*
|--------------------------------------------------------------------------
| Check Login
|--------------------------------------------------------------------------
*/

if (!in_array($currentPage, $publicPages)) {


    requireLogin();

    validateRole();


}



/*
|--------------------------------------------------------------------------
| Cashier Restriction
|--------------------------------------------------------------------------
*/

if (
    getRole() === "Cashier"
    &&
    !in_array($currentPage, $cashierPages)
) {


    header(
        "Location: unauthorized.php"
    );

    exit;

}


?>